import assert from "node:assert/strict";
import { prisma } from "../../src/lib/db";
import { registerUser, authenticate, createSession, findSessionUser, revokeSession, issueClaimCode, allowAuthAttempt } from "../../src/lib/auth/service";
import { tokenHash } from "../../src/lib/auth/credentials";
import { notifyOnce } from "../../src/lib/notify";

async function main() {
  require("../db/test-target.cjs").assertTestDatabase();
  const suffix = Date.now();
  const password = "correct horse battery staple";
  const legacy = await prisma.user.create({ data: { name: `legacy-${suffix}` } });
  const original = await prisma.transaction.create({ data: { userId: legacy.id, occurredAt: new Date(), amount: -1234, kind: "EXPENSE", merchantRaw: "legacy-private", merchantNorm: "legacy-private", source: "MANUAL" } });
  const a = await registerUser({ name: "A", email: ` A${suffix}@example.com `, password });
  assert.equal(a.email, `a${suffix}@example.com`);
  assert.equal(await prisma.transaction.count({ where: { userId: a.id } }), 0);
  assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: legacy.id } })).email, null);
  await assert.rejects(registerUser({ name: "duplicate", email: a.email!, password }));
  const duplicate = await Promise.allSettled([1, 2].map(() => registerUser({ name: "race", email: `race${suffix}@example.com`, password })));
  assert.equal(duplicate.filter(x => x.status === "fulfilled").length, 1);
  assert.equal((await authenticate(a.email!, password)).id, a.id);
  const wrong = await authenticate(a.email!, password + "x").catch(e => e.message);
  const unknown = await authenticate(`missing${suffix}@example.com`, password).catch(e => e.message);
  assert.equal(wrong, unknown);
  const session = await createSession(a.id);
  assert.equal((await findSessionUser(session.token))?.id, a.id);
  assert.equal(await prisma.session.findUnique({ where: { tokenHash: session.token } }), null);
  assert.ok(await prisma.session.findUnique({ where: { tokenHash: tokenHash(session.token) } }));
  assert.equal(await findSessionUser("f".repeat(64)), null);
  assert.equal(await findSessionUser(session.token, session.expiresAt), null);
  await revokeSession(session.token);
  assert.equal(await findSessionUser(session.token), null);
  await assert.rejects(registerUser({ name: "claim", email: `bad${suffix}@example.com`, password, claimCode: "f".repeat(64) }));
  const expired = await issueClaimCode(legacy.id);
  await prisma.user.update({ where: { id: legacy.id }, data: { claimExpiresAt: new Date(0) } });
  await assert.rejects(registerUser({ name: "claim", email: `expired${suffix}@example.com`, password, claimCode: expired.token }));
  const code = await issueClaimCode(legacy.id);
  const b = await registerUser({ name: "B", email: `b${suffix}@example.com`, password, claimCode: code.token });
  assert.equal(b.id, legacy.id);
  assert.equal((await prisma.transaction.findUniqueOrThrow({ where: { id: original.id } })).userId, b.id);
  await assert.rejects(registerUser({ name: "reuse", email: `reuse${suffix}@example.com`, password, claimCode: code.token }));
  await assert.rejects(issueClaimCode(b.id));
  assert.equal(await notifyOnce(a.id, `shared${suffix}`, "DUE", "a", "a"), true);
  assert.equal(await notifyOnce(b.id, `shared${suffix}`, "DUE", "b", "b"), true);
  assert.equal(await notifyOnce(a.id, `shared${suffix}`, "DUE", "a", "a"), false);
  await prisma.authRateLimit.deleteMany();
  const now = new Date();
  const attempts = await Promise.all(Array.from({ length: 15 }, () => allowAuthAttempt(`rate${suffix}@example.com`, now)));
  assert.equal(attempts.filter(Boolean).length, 10);
  assert.equal(await allowAuthAttempt(`rate${suffix}@example.com`, new Date(+now + 900001)), true);
  await prisma.authRateLimit.deleteMany();
  console.log("PASS: signup uniqueness/concurrency, password, sessions, legacy claim expiry/replay, per-user notifications, concurrent rate limit");
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => prisma.$disconnect());
